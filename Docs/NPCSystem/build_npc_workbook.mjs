const workbook = Workbook.create();

function addSheet(name, rows, options = {}) {
  const sheet = workbook.worksheets.add(name);
  sheet.showGridLines = false;
  const rowCount = rows.length;
  const colCount = Math.max(...rows.map((row) => row.length));
  sheet.getRangeByIndexes(0, 0, rowCount, colCount).values = rows;

  const header = sheet.getRangeByIndexes(0, 0, 1, colCount);
  header.format = {
    fill: "#27364A",
    font: { bold: true, color: "#FFFFFF" },
    wrapText: true,
  };

  if (rowCount > 1) {
    const body = sheet.getRangeByIndexes(1, 0, rowCount - 1, colCount);
    body.format = {
      wrapText: true,
      font: { color: "#1F2933" },
    };
  }

  const used = sheet.getRangeByIndexes(0, 0, rowCount, colCount);
  used.format = {
    wrapText: true,
    verticalAlignment: "top",
  };

  for (let c = 0; c < colCount; c += 1) {
    const width = options.widths?.[c] ?? 150;
    sheet.getRangeByIndexes(0, c, rowCount, 1).format.columnWidthPx = width;
  }

  if (sheet.freezePanes?.freezeRows) {
    sheet.freezePanes.freezeRows(1);
  }

  return sheet;
}

